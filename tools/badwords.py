#!/usr/bin/env python3
"""Hash the pet's swear list into a C header, so the public repo never shows the words.

List format: one lowercase word per line; `#` starts a comment. A trailing `*`
matches any word starting with the stem (at least 3 letters), e.g. `frick*`
also catches `fricking`. The list itself stays out of git.
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_LIST = ROOT / "art/badwords.txt"
DEFAULT_OUT = ROOT / "keyboards/cosmos/anex/keymaps/via/badword_hashes.h"
# Firmware tracks at most this many letters per word (WORDS_MAX_LEN in words.h).
MAX_LEN = 16
MIN_STEM = 3
WORD = re.compile(r"^[a-z]+$")


def fnv1a(text):
    """32-bit FNV-1a; must match words_hash() in words.c."""
    h = 0x811C9DC5
    for byte in text.encode():
        h ^= byte
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def parse(text):
    """Return (exact words, prefix stems)."""
    exact, prefix = set(), set()
    for number, raw in enumerate(text.splitlines(), 1):
        entry = raw.split("#", 1)[0].strip().lower()
        if not entry:
            continue
        stem = entry[:-1] if entry.endswith("*") else entry
        if not WORD.match(stem):
            raise ValueError(f"line {number}: only letters a-z, optionally ending in *")
        if len(stem) > MAX_LEN:
            raise ValueError(f"line {number}: longer than {MAX_LEN} letters never matches")
        if entry.endswith("*"):
            if len(stem) < MIN_STEM:
                raise ValueError(f"line {number}: stems need at least {MIN_STEM} letters")
            prefix.add(stem)
        else:
            exact.add(entry)
    return exact, prefix


def array(name, words):
    hashes = sorted(fnv1a(w) for w in words)
    body = ", ".join(f"0x{h:08x}" for h in hashes) or "0"
    return [f"static const uint32_t {name}[] = {{{body}}};", f"#define {name.upper()}_COUNT {len(hashes)}"]


def render(exact, prefix):
    lines = [
        "// Generated by tools/badwords.py from art/badwords.txt, which is not in git;",
        "// regenerate rather than edit.",
        "",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        *array("badword_exact", exact),
        *array("badword_prefix", prefix),
    ]
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--list", type=Path, default=DEFAULT_LIST)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="exit 1 if the header differs from the list")
    args = parser.parse_args(argv)

    if not args.list.exists():
        if args.check:
            # CI and fresh clones don't have the list; the committed header stands.
            return 0
        print(f"{args.list} not found; see art/badwords.example.txt", file=sys.stderr)
        return 1
    text = render(*parse(args.list.read_text()))
    if args.check:
        if not args.out.exists() or args.out.read_text() != text:
            print(f"{args.out} is out of date with {args.list.name}", file=sys.stderr)
            return 1
        return 0
    args.out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
