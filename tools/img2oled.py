#!/usr/bin/env python3
"""Convert a monochrome image to a QMK OLED raw bitmap header."""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_IN = ROOT / "KB Logo.png"
DEFAULT_OUT = ROOT / "keyboards/cosmos/anex/keymaps/via/logo.h"
DEFAULT_NAME = "anex_logo"


def pack(pixels, width, height):
    """Pack row-major booleans into SSD1306 page order.

    Each byte is one column of an 8-pixel-tall page, least significant bit on top,
    which is the layout oled_write_raw_P() expects.
    """
    if height % 8:
        raise ValueError(f"height {height} is not a multiple of 8")
    if len(pixels) != width * height:
        raise ValueError(f"expected {width * height} pixels, got {len(pixels)}")
    out = bytearray()
    for page in range(height // 8):
        for x in range(width):
            byte = 0
            for bit in range(8):
                if pixels[(page * 8 + bit) * width + x]:
                    byte |= 1 << bit
            out.append(byte)
    return bytes(out)


def load(path, threshold=128):
    from PIL import Image

    image = Image.open(path).convert("L")
    return [value >= threshold for value in image.get_flattened_data()], image.width, image.height


def render(name, data, width, height, source_name):
    lines = [
        f"// Generated by tools/img2oled.py from {source_name}; regenerate rather than edit.",
        "",
        "#pragma once",
        "",
        f"#define {name.upper()}_WIDTH {width}",
        f"#define {name.upper()}_HEIGHT {height}",
        "",
        f"static const char PROGMEM {name}[] = {{",
    ]
    for start in range(0, len(data), 16):
        lines.append("    " + " ".join(f"0x{b:02x}," for b in data[start : start + 16]))
    lines.append("};")
    return "\n".join(lines) + "\n"


def generate(path, name):
    pixels, width, height = load(path)
    return render(name, pack(pixels, width, height), width, height, Path(path).name)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--in", dest="source", type=Path, default=DEFAULT_IN)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--name", default=DEFAULT_NAME)
    parser.add_argument("--check", action="store_true", help="exit 1 if --out differs from the generated header")
    args = parser.parse_args(argv)

    text = generate(args.source, args.name)
    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is out of date with {args.source.name}", file=sys.stderr)
            return 1
        return 0

    args.out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
