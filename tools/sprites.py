#!/usr/bin/env python3
"""Convert ASCII-art sprite sheets into QMK OLED page-packed C headers.

Sheet format: a `[name]` line starts each sprite, followed by its rows, with
`#` for a lit pixel and `.` for an unlit one. Lines starting with `;` and blank
lines are ignored. Every sprite must have the same size, with a height that is
a multiple of 8.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from img2oled import pack  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
KEYMAP = ROOT / "keyboards/cosmos/anex/keymaps/via"
DEFAULT_SHEET = ROOT / "art/pet.txt"
DEFAULT_PREFIX = "pet"


def parse(text):
    """Return [(name, rows)] in sheet order."""
    sprites = []
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith(";"):
            continue
        if line.startswith("[") and line.endswith("]"):
            sprites.append((line[1:-1], []))
            continue
        if not sprites:
            raise ValueError(f"line {number}: pixels before the first [name]")
        if set(line) - {"#", "."}:
            raise ValueError(f"line {number}: only '#' and '.' are allowed")
        sprites[-1][1].append(line)
    if not sprites:
        raise ValueError("no sprites found")
    return sprites


def size(sprites):
    name, rows = sprites[0]
    width, height = len(rows[0]) if rows else 0, len(rows)
    for name, rows in sprites:
        if len(rows) != height or any(len(row) != width for row in rows):
            raise ValueError(f"sprite {name} is not {width}x{height}")
    if height % 8:
        raise ValueError(f"sprite height {height} is not a multiple of 8")
    return width, height


def to_bytes(rows):
    width = len(rows[0])
    pixels = [ch == "#" for row in rows for ch in row]
    return pack(pixels, width, len(rows))


def render_ids(prefix, sprites, width, height, source_name):
    upper = prefix.upper()
    lines = [
        f"// Generated by tools/sprites.py from {source_name}; regenerate rather than edit.",
        "",
        "#pragma once",
        "",
        f"#define {upper}_SPRITE_WIDTH {width}",
        f"#define {upper}_SPRITE_HEIGHT {height}",
        "",
        "enum {",
    ]
    lines += [f"    {upper}_SPRITE_{name.upper()}," for name, _ in sprites]
    lines += [f"    {upper}_SPRITE_COUNT", "};"]
    return "\n".join(lines) + "\n"


def render_data(prefix, sprites, width, height, source_name):
    lines = [
        f"// Generated by tools/sprites.py from {source_name}; regenerate rather than edit.",
        "",
        "#pragma once",
        "",
        f'#include "{prefix}_sprite_ids.h"',
        "",
        f"static const char PROGMEM {prefix}_sprites[{prefix.upper()}_SPRITE_COUNT][{width * height // 8}] = {{",
    ]
    for name, rows in sprites:
        data = to_bytes(rows)
        lines.append(f"    [{prefix.upper()}_SPRITE_{name.upper()}] = {{")
        for start in range(0, len(data), 16):
            lines.append("        " + " ".join(f"0x{b:02x}," for b in data[start : start + 16]))
        lines.append("    },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def generate(sheet_path, prefix):
    """Return {output filename: text}."""
    sheet_path = Path(sheet_path).resolve()
    sprites = parse(sheet_path.read_text())
    width, height = size(sprites)
    source = sheet_path.relative_to(ROOT) if sheet_path.is_relative_to(ROOT) else sheet_path.name
    return {
        f"{prefix}_sprite_ids.h": render_ids(prefix, sprites, width, height, source),
        f"{prefix}_sprites.h": render_data(prefix, sprites, width, height, source),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sheet", type=Path, default=DEFAULT_SHEET)
    parser.add_argument("--prefix", default=DEFAULT_PREFIX)
    parser.add_argument("--out-dir", type=Path, default=KEYMAP)
    parser.add_argument("--check", action="store_true", help="exit 1 if the headers differ from the sheet")
    args = parser.parse_args(argv)

    stale = False
    for name, text in generate(args.sheet, args.prefix).items():
        path = args.out_dir / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f"{path} is out of date with {args.sheet.name}", file=sys.stderr)
                stale = True
        else:
            path.write_text(text)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
