#!/usr/bin/env python3
"""Generate a QMK keymap.c from a VIA keymap backup (the .layout.json VIA exports)."""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_VIA = ROOT / "via-layout.json"
DEFAULT_KEYBOARD = ROOT / "keyboards/cosmos/anex/keyboard.json"
DEFAULT_OUT = ROOT / "keyboards/cosmos/anex/keymaps/via/keymap.c"

# Keys per line in the generated LAYOUT() calls, in keyboard.json layout order.
DEFAULT_ROWS = (14, 14, 14, 12, 12, 8, 14)

# VIA exports QMK's pre-0.27 names. Each maps to the current name for the same
# keycode value, so the flashed default is identical to what VIA stores.
LEGACY_ALIASES = {
    "RESET": "QK_BOOT",
    "DEBUG": "DB_TOGG",
    "EEP_RST": "EE_CLR",
    # VIA's RGB_* are the underglow codes, which also drive RGB Matrix.
    "RGB_TOG": "UG_TOGG",
    "RGB_MOD": "UG_NEXT",
    "RGB_RMOD": "UG_PREV",
    "RGB_HUI": "UG_HUEU",
    "RGB_HUD": "UG_HUED",
    "RGB_SAI": "UG_SATU",
    "RGB_SAD": "UG_SATD",
    "RGB_VAI": "UG_VALU",
    "RGB_VAD": "UG_VALD",
    "RGB_SPI": "UG_SPDU",
    "RGB_SPD": "UG_SPDD",
    "KC_MS_U": "MS_UP",
    "KC_MS_UP": "MS_UP",
    "KC_MS_D": "MS_DOWN",
    "KC_MS_DOWN": "MS_DOWN",
    "KC_MS_L": "MS_LEFT",
    "KC_MS_LEFT": "MS_LEFT",
    "KC_MS_R": "MS_RGHT",
    "KC_MS_RIGHT": "MS_RGHT",
    "KC_WH_U": "MS_WHLU",
    "KC_MS_WH_UP": "MS_WHLU",
    "KC_WH_D": "MS_WHLD",
    "KC_MS_WH_DOWN": "MS_WHLD",
    "KC_WH_L": "MS_WHLL",
    "KC_MS_WH_LEFT": "MS_WHLL",
    "KC_WH_R": "MS_WHLR",
    "KC_MS_WH_RIGHT": "MS_WHLR",
    "KC_ACL0": "MS_ACL0",
    "KC_MS_ACCEL0": "MS_ACL0",
    "KC_ACL1": "MS_ACL1",
    "KC_MS_ACCEL1": "MS_ACL1",
    "KC_ACL2": "MS_ACL2",
    "KC_MS_ACCEL2": "MS_ACL2",
    **{f"KC_BTN{n}": f"MS_BTN{n}" for n in range(1, 9)},
    **{f"KC_MS_BTN{n}": f"MS_BTN{n}" for n in range(1, 9)},
}

# Codes VIA writes at matrix positions that no physical key uses; not worth a warning.
EMPTY_CODES = {"KC_NO", "KC_TRNS"}

IDENT = re.compile(r"\b[A-Z_][A-Z0-9_]*\b")
LAYER_REF = re.compile(r"\b(?:MO|TG|TO|TT|OSL|DF|PDF|LT|LM)\(\s*(\d+)")


def translate(code):
    return IDENT.sub(lambda m: LEGACY_ALIASES.get(m.group(0), m.group(0)), code)


def layer_refs(code):
    return [int(n) for n in LAYER_REF.findall(code)]


def load_keyboard(info):
    """Return (matrix_rows, matrix_cols, layout positions) from keyboard.json data."""
    rows = len(info["matrix_pins"]["rows"])
    cols = len(info["matrix_pins"]["cols"])
    if info.get("split", {}).get("enabled"):
        rows *= 2
    positions = [tuple(key["matrix"]) for key in info["layouts"]["LAYOUT"]["layout"]]
    return rows, cols, positions


def via_to_layout(via, matrix_rows, matrix_cols, positions):
    """Reorder VIA's row-major matrix layers into LAYOUT() argument order.

    Returns (layers, warnings).
    """
    warnings = []
    used = set(positions)
    layers = []
    for index, flat in enumerate(via["layers"]):
        if len(flat) != matrix_rows * matrix_cols:
            raise ValueError(f"layer {index} has {len(flat)} keys, expected {matrix_rows * matrix_cols}")
        layers.append([translate(flat[r * matrix_cols + c]) for r, c in positions])
        for r in range(matrix_rows):
            for c in range(matrix_cols):
                code = flat[r * matrix_cols + c]
                if (r, c) not in used and code not in EMPTY_CODES:
                    warnings.append(f"layer {index}: {code} at unused matrix position ({r},{c}) dropped")
    for index, layer in enumerate(layers):
        for code in layer:
            for target in layer_refs(code):
                if target >= len(layers):
                    warnings.append(f"layer {index}: {code} targets layer {target}, only {len(layers)} exist")
    return layers, warnings


def render(layers, rows, source_name):
    if any(sum(rows) != len(layer) for layer in layers):
        raise ValueError(f"row sizes sum to {sum(rows)}, layout has {len(layers[0])} keys")
    out = [
        f"// Generated by tools/via2keymap.py from {source_name}; regenerate rather than edit.",
        "",
        "#include QMK_KEYBOARD_H",
        "",
        "const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {",
    ]
    for index, layer in enumerate(layers):
        width = max(len(code) for code in layer) + 1
        out.append(f"    [{index}] = LAYOUT(")
        start = 0
        for count in rows:
            chunk = layer[start : start + count]
            start += count
            last_line = start == len(layer)
            cells = [code + ("" if last_line and i == len(chunk) - 1 else ",") for i, code in enumerate(chunk)]
            out.append("        " + " ".join(cell.ljust(width) for cell in cells).rstrip())
        out.append("    ),")
    out.append("};")
    return "\n".join(out) + "\n"


def generate(via_path, keyboard_path, rows=DEFAULT_ROWS):
    via = json.loads(Path(via_path).read_text())
    info = json.loads(Path(keyboard_path).read_text())
    matrix_rows, matrix_cols, positions = load_keyboard(info)
    layers, warnings = via_to_layout(via, matrix_rows, matrix_cols, positions)
    return render(layers, rows, Path(via_path).name), warnings


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--via", type=Path, default=DEFAULT_VIA)
    parser.add_argument("--keyboard", type=Path, default=DEFAULT_KEYBOARD)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="exit 1 if --out differs from the generated keymap")
    args = parser.parse_args(argv)

    text, warnings = generate(args.via, args.keyboard)
    for warning in warnings:
        print(f"warning: {warning}", file=sys.stderr)

    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        if current != text:
            print(f"{args.out} is out of date with {args.via.name}", file=sys.stderr)
            return 1
        return 0

    args.out.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
